#!/usr/bin/env node
// Generates what the two implementations of Shannon consume from the one product spec:
//   design/tokens.json      -> design/generated/ShannonDesignTokens.generated.swift, shannon-tokens.css, shannon-tokens.ts
//   design/strings.ja.json  -> design/generated/ShannonStrings.generated.swift, shannon-strings.ja.ts
//   docs/product/feature-matrix.json -> docs/product/feature-matrix.md
// Run without arguments to write the files, with --check to fail when any of them is stale.
// No dependencies beyond Node.js. See docs/product/README.md.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const defaultRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const sourcePaths = {
  tokens: 'design/tokens.json',
  strings: 'design/strings.ja.json',
  matrix: 'docs/product/feature-matrix.json',
};

export const appleGeneratedFolder = 'apps/ios/Sources/ShannonAppCore/DesignSystem/Generated';
export const surfaces = ['ios', 'macos', 'windows'];
export const surfaceTitles = { ios: 'iOS', macos: 'macOS', windows: 'Windows' };
export const statuses = ['yes', 'partial', 'no', 'not_applicable', 'planned', 'unknown'];
const statusMarks = { yes: '○', partial: '△', no: '×', not_applicable: '—', planned: '予定', unknown: '？' };

const header = (source) => `GENERATED by scripts/generate-product-spec.mjs from ${source}. Do not edit; change the source and run the script.`;

function hexNumber(value) { return `0x${value.slice(1).toUpperCase()}`; }
function kebab(name) { return name.replace(/([a-z0-9])([A-Z])/gu, '$1-$2').toLowerCase(); }
function number(value) { return Number.isInteger(value) ? String(value) : String(value); }

// ---------------------------------------------------------------- tokens

export function renderTokensSwift(tokens) {
  const lines = [`// ${header(sourcePaths.tokens)}`, '', 'import CoreGraphics', ''];
  lines.push('/// The shared design tokens of Shannon (iOS, macOS and Windows use the same values).');
  lines.push('public enum ShannonGeneratedTokens {');
  lines.push('    public enum Color {');
  for (const [title, mode] of [['Light', 'light'], ['Dark', 'dark']]) {
    lines.push(`        public enum ${title} {`);
    for (const [name, role] of Object.entries(tokens.color.roles)) {
      lines.push(`            /// ${role.meaning}`);
      lines.push(`            public static let ${name}: UInt = ${hexNumber(role[mode])}`);
    }
    lines.push('        }');
  }
  lines.push('        public enum Fixed {');
  for (const [name, entry] of Object.entries(tokens.color.fixed)) {
    lines.push(`            /// ${entry.meaning}`);
    lines.push(`            public static let ${name}: UInt = ${hexNumber(entry.value)}`);
  }
  lines.push('        }', '    }', '');
  lines.push('    public struct TextStyle: Equatable, Sendable {');
  lines.push('        public let size: CGFloat', '        public let lineHeight: CGFloat', '        public let weight: Int');
  lines.push('        /// The SwiftUI text style this entry stands for (Dynamic Type scales it).');
  lines.push('        public let swiftTextStyle: String', '    }', '');
  lines.push('    public enum Typography {');
  for (const [name, style] of Object.entries(tokens.typography.scale)) {
    lines.push(`        public static let ${name} = TextStyle(size: ${number(style.size)}, lineHeight: ${number(style.lineHeight)}, weight: ${style.weight}, swiftTextStyle: "${style.swiftTextStyle}")`);
  }
  if (tokens.typography.reading) {
    lines.push(`        /// ${tokens.typography.reading.about}`);
    lines.push(`        public static let readingLineHeightRatio: CGFloat = ${number(tokens.typography.reading.lineHeightRatio)}`);
  }
  lines.push('    }', '');
  if (tokens.typography.desktop) {
    lines.push('    /// Wide screens (macOS and Windows): fixed sizes, one step below the phone scale. The phone keeps Dynamic Type.');
    lines.push('    public enum DesktopTypography {');
    for (const [name, style] of Object.entries(tokens.typography.desktop.scale)) {
      lines.push(`        public static let ${name} = TextStyle(size: ${number(style.size)}, lineHeight: ${number(style.lineHeight)}, weight: ${style.weight}, swiftTextStyle: "${tokens.typography.scale[name]?.swiftTextStyle ?? name}")`);
    }
    lines.push('    }', '');
  }
  for (const [title, group] of [['Spacing', tokens.spacing], ['Radius', tokens.radius], ['Size', tokens.size]]) {
    lines.push(`    public enum ${title} {`);
    for (const [name, value] of Object.entries(group)) lines.push(`        public static let ${name}: CGFloat = ${number(value)}`);
    lines.push('    }', '');
  }
  lines.push('    /// Durations in seconds.', '    public enum Motion {');
  for (const [name, entry] of Object.entries(tokens.motion.duration)) {
    lines.push(`        /// ${entry.meaning}`);
    lines.push(`        public static let ${name}: Double = ${number(entry.seconds)}`);
  }
  lines.push('    }', '}', '');
  return lines.join('\n');
}

export function renderTokensCss(tokens) {
  const colors = (mode) => Object.entries(tokens.color.roles).map(([name, role]) => `  --shannon-color-${kebab(name)}: ${role[mode].toUpperCase()};`);
  const lines = [`/* ${header(sourcePaths.tokens)} */`, ''];
  lines.push(':root {', '  color-scheme: light dark;', ...colors('light'));
  for (const [name, entry] of Object.entries(tokens.color.fixed)) lines.push(`  --shannon-color-${kebab(name)}: ${entry.value.toUpperCase()};`);
  lines.push(`  --shannon-font-sans: ${tokens.typography.fontFamily.sans.map(cssFont).join(', ')};`);
  lines.push(`  --shannon-font-mono: ${tokens.typography.fontFamily.mono.map(cssFont).join(', ')};`);
  for (const [name, style] of Object.entries(tokens.typography.scale)) {
    lines.push(`  --shannon-font-size-${kebab(name)}: ${number(style.size)}px;`);
    lines.push(`  --shannon-line-height-${kebab(name)}: ${number(style.lineHeight)}px;`);
    lines.push(`  --shannon-font-weight-${kebab(name)}: ${style.weight};`);
  }
  for (const [name, value] of Object.entries(tokens.typography.weight)) lines.push(`  --shannon-weight-${kebab(name)}: ${value};`);
  if (tokens.typography.reading) lines.push(`  --shannon-line-height-reading: ${number(tokens.typography.reading.lineHeightRatio)};`);
  for (const [name, value] of Object.entries(tokens.spacing)) lines.push(`  --shannon-space-${kebab(name)}: ${number(value)}px;`);
  for (const [name, value] of Object.entries(tokens.radius)) lines.push(`  --shannon-radius-${kebab(name)}: ${number(value)}px;`);
  for (const [name, value] of Object.entries(tokens.size)) lines.push(`  --shannon-size-${kebab(name)}: ${number(value)}px;`);
  for (const [name, entry] of Object.entries(tokens.motion.duration)) lines.push(`  --shannon-duration-${kebab(name)}: ${Math.round(entry.seconds * 1000)}ms;`);
  for (const [name, style] of Object.entries(tokens.typography.desktop?.scale ?? {})) {
    lines.push(`  --shannon-desktop-font-size-${kebab(name)}: ${number(style.size)}px;`);
    lines.push(`  --shannon-desktop-line-height-${kebab(name)}: ${number(style.lineHeight)}px;`);
  }
  lines.push('}', '');
  if (tokens.typography.desktop) {
    lines.push('/* Wide screens (macOS and Windows): set data-shannon-density="desktop" on <html> and keep using the plain names. */');
    lines.push(':root[data-shannon-density="desktop"] {');
    for (const [name, style] of Object.entries(tokens.typography.desktop.scale)) {
      lines.push(`  --shannon-font-size-${kebab(name)}: ${number(style.size)}px;`);
      lines.push(`  --shannon-line-height-${kebab(name)}: ${number(style.lineHeight)}px;`);
      lines.push(`  --shannon-font-weight-${kebab(name)}: ${style.weight};`);
    }
    lines.push('}', '');
  }
  lines.push('@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', ...colors('dark').map((line) => `  ${line}`), '  }', '}', '');
  lines.push(':root[data-theme="dark"] {', ...colors('dark'), '}', '');
  return lines.join('\n');
}

function cssFont(name) { return /^[a-z-]+$/u.test(name) ? name : `"${name}"`; }

export function renderTokensTs(tokens) {
  const value = {
    color: {
      light: Object.fromEntries(Object.entries(tokens.color.roles).map(([name, role]) => [name, role.light.toUpperCase()])),
      dark: Object.fromEntries(Object.entries(tokens.color.roles).map(([name, role]) => [name, role.dark.toUpperCase()])),
      fixed: Object.fromEntries(Object.entries(tokens.color.fixed).map(([name, entry]) => [name, entry.value.toUpperCase()])),
    },
    typography: {
      fontFamily: tokens.typography.fontFamily,
      scale: Object.fromEntries(Object.entries(tokens.typography.scale).map(([name, style]) => [name, { size: style.size, lineHeight: style.lineHeight, weight: style.weight }])),
      desktopScale: Object.fromEntries(Object.entries(tokens.typography.desktop?.scale ?? {}).map(([name, style]) => [name, { size: style.size, lineHeight: style.lineHeight, weight: style.weight }])),
      weight: tokens.typography.weight,
      ...(tokens.typography.reading ? { readingLineHeightRatio: tokens.typography.reading.lineHeightRatio } : {}),
    },
    spacing: tokens.spacing,
    radius: tokens.radius,
    size: tokens.size,
    motionSeconds: Object.fromEntries(Object.entries(tokens.motion.duration).map(([name, entry]) => [name, entry.seconds])),
  };
  return [
    `// ${header(sourcePaths.tokens)}`,
    '',
    '/** The shared design tokens of Shannon. The CSS variables of the same values are in shannon-tokens.css. */',
    `export const shannonTokens = ${JSON.stringify(value, null, 2)} as const;`,
    '',
    'export type ShannonColorRole = keyof typeof shannonTokens.color.light;',
    '',
    '/** The CSS variable of a colour role, e.g. `var(--shannon-color-text-primary)`. */',
    'export function shannonColorVar(role: ShannonColorRole): string {',
    "  return `var(--shannon-color-${role.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()})`;",
    '}',
    '',
  ].join('\n');
}

// ---------------------------------------------------------------- strings

export function stringParams(text) {
  return [...new Set([...text.matchAll(/\{([A-Za-z][A-Za-z0-9]*)\}/gu)].map((match) => match[1]))];
}

export function swiftIdentifier(key) {
  return key.split('.').map((part, index) => (index === 0 ? part : part[0].toUpperCase() + part.slice(1))).join('');
}

export function swiftLiteral(text) {
  const escaped = text.replace(/\\/gu, '\\\\').replace(/"/gu, '\\"').replace(/\n/gu, '\\n');
  return `"${escaped.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/gu, '\\($1)')}"`;
}

export function renderStringsSwift(strings) {
  const lines = [`// ${header(sourcePaths.strings)}`, ''];
  lines.push('/// The shared user-facing copy of Shannon (iOS, macOS and Windows show the same words).');
  lines.push('public enum ShannonGeneratedStrings {');
  for (const entry of strings.strings) {
    const params = stringParams(entry.text);
    lines.push(`    /// \`${entry.key}\`${entry.verbatim ? ' (verbatim: a promise to the owner, do not reword)' : ''}`);
    if (params.length === 0) lines.push(`    public static let ${swiftIdentifier(entry.key)} = ${swiftLiteral(entry.text)}`);
    else lines.push(`    public static func ${swiftIdentifier(entry.key)}(${params.map((name) => `${name}: String`).join(', ')}) -> String { ${swiftLiteral(entry.text)} }`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

export function renderStringsTs(strings) {
  const lines = [`// ${header(sourcePaths.strings)}`, ''];
  lines.push('/** The shared user-facing copy of Shannon, by stable key. `{name}` marks a value to insert. */');
  lines.push('export const shannonStrings = {');
  for (const entry of strings.strings) lines.push(`  ${JSON.stringify(entry.key)}: ${JSON.stringify(entry.text)},`);
  lines.push('} as const;', '');
  lines.push('export type ShannonStringKey = keyof typeof shannonStrings;', '');
  lines.push('/** Keys whose wording is a promise to the owner: show them exactly as they are. */');
  lines.push(`export const shannonVerbatimKeys: readonly ShannonStringKey[] = ${JSON.stringify(strings.strings.filter((entry) => entry.verbatim).map((entry) => entry.key), null, 2)};`, '');
  const decided = strings.strings.filter((entry) => entry.decided);
  if (decided.length) {
    lines.push('/** Wording the owner decided, with what each implementation showed before (to find what must be replaced). */');
    lines.push(`export const shannonDecidedWording: Readonly<Record<string, { decided: string; windowsBefore?: string; macBefore?: string }>> = ${JSON.stringify(Object.fromEntries(decided.map((entry) => [entry.key, { decided: entry.decided, ...(entry.windowsNow ? { windowsBefore: entry.windowsNow } : {}), ...(entry.macNow ? { macBefore: entry.macNow } : {}) }])), null, 2)};`, '');
  }
  lines.push('export function shannonString(key: ShannonStringKey, params: Readonly<Record<string, string | number>> = {}): string {');
  lines.push('  return shannonStrings[key].replace(/\\{([A-Za-z][A-Za-z0-9]*)\\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));');
  lines.push('}', '');
  return lines.join('\n');
}

// ---------------------------------------------------------------- feature matrix

export function matrixCounts(matrix) {
  const counts = Object.fromEntries(surfaces.map((surface) => [surface, Object.fromEntries(statuses.map((status) => [status, 0]))]));
  for (const feature of matrix.features) for (const surface of surfaces) counts[surface][feature.surfaces[surface].status] += 1;
  return counts;
}

function cellText(cell) { return statusMarks[cell.status] ?? cell.status; }

function cellNote(cell) {
  const parts = [];
  if (cell.status === 'planned') parts.push(`ブランチ \`${cell.branch}\``);
  if (cell.status === 'not_applicable') parts.push(cell.reason);
  if (cell.note) parts.push(cell.note);
  return parts.join('。');
}

function tableText(text) { return String(text).replace(/\|/gu, '｜').replace(/\n/gu, ' '); }

export function renderMatrixMarkdown(matrix) {
  const counts = matrixCounts(matrix);
  const lines = [`<!-- ${header(sourcePaths.matrix)} -->`, '', '# Shannon 機能の一覧表（iOS・macOS・Windows）', ''];
  lines.push(`元の定義は \`${sourcePaths.matrix}\`。この表は \`node scripts/generate-product-spec.mjs\` で作り直す。`);
  lines.push(`Apple 側（iOS・macOS）は \`${matrix.baseline.apple.commit}\`（${matrix.baseline.apple.date}）のコード、Windows 側は ${matrix.baseline.windows.read} に読んだ \`${matrix.baseline.windows.source}\` から埋めた。`, '');
  lines.push('記号: ○ ある／△ 一部だけある／× ない／— その画面には当てはまらない／予定 作業中のブランチにある／？ 分からない。', '');
  lines.push('## 件数', '', `機能は全部で ${matrix.features.length} 件。`, '');
  lines.push('| 画面 | ○ ある | △ 一部 | × ない | — 当てはまらない | 予定 | ？ 不明 |', '|---|---:|---:|---:|---:|---:|---:|');
  for (const surface of surfaces) {
    const row = counts[surface];
    lines.push(`| ${surfaceTitles[surface]} | ${row.yes} | ${row.partial} | ${row.no} | ${row.not_applicable} | ${row.planned} | ${row.unknown} |`);
  }
  lines.push('');
  for (const area of matrix.areas) {
    const features = matrix.features.filter((feature) => feature.area === area.id);
    if (features.length === 0) continue;
    lines.push(`## ${area.title}（\`${area.id}\`）`, '');
    if (area.place) lines.push(`決まった構成での場所: ${area.place}`, '');
    lines.push('| id | 機能 | iOS | macOS | Windows |', '|---|---|:-:|:-:|:-:|');
    const notes = [];
    for (const feature of features) {
      const scope = feature.scope === 'desktop' ? '【デスクトップの追加】' : feature.scope === 'phone' ? '【iPhone だけ】' : '';
      lines.push(`| \`${feature.id}\` | **${tableText(feature.title)}**${scope} ${tableText(feature.description)} | ${surfaces.map((surface) => cellText(feature.surfaces[surface])).join(' | ')} |`);
      for (const surface of surfaces) {
        const note = cellNote(feature.surfaces[surface]);
        if (note) notes.push(`- \`${feature.id}\` ${surfaceTitles[surface]}（${cellText(feature.surfaces[surface])}）: ${note}`);
      }
    }
    if (notes.length) lines.push('', ...notes);
    lines.push('');
  }
  return lines.join('\n');
}

// ---------------------------------------------------------------- outputs

export function readSources(root = defaultRoot) {
  const read = (path) => JSON.parse(readFileSync(resolve(root, path), 'utf8'));
  return { tokens: read(sourcePaths.tokens), strings: read(sourcePaths.strings), matrix: read(sourcePaths.matrix) };
}

/** Every generated file and its current content, by repository-relative path. */
export function outputs({ tokens, strings, matrix }) {
  return {
    'design/generated/ShannonDesignTokens.generated.swift': renderTokensSwift(tokens),
    'design/generated/shannon-tokens.css': renderTokensCss(tokens),
    'design/generated/shannon-tokens.ts': renderTokensTs(tokens),
    'design/generated/ShannonStrings.generated.swift': renderStringsSwift(strings),
    // The same Swift, compiled into the shared Apple package (iOS and macOS read these values).
    [`${appleGeneratedFolder}/ShannonDesignTokens.generated.swift`]: renderTokensSwift(tokens),
    [`${appleGeneratedFolder}/ShannonStrings.generated.swift`]: renderStringsSwift(strings),
    'design/generated/shannon-strings.ja.ts': renderStringsTs(strings),
    'docs/product/feature-matrix.md': renderMatrixMarkdown(matrix),
  };
}

/** The generated files that are missing or differ from what the sources produce. */
export function staleOutputs(root = defaultRoot) {
  const stale = [];
  for (const [path, content] of Object.entries(outputs(readSources(root)))) {
    const absolute = resolve(root, path);
    if (!existsSync(absolute) || readFileSync(absolute, 'utf8') !== content) stale.push(path);
  }
  return stale;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = staleOutputs();
    if (stale.length) {
      console.error('Generated product spec files are stale (run: node scripts/generate-product-spec.mjs):');
      for (const path of stale) console.error(`- ${path}`);
      process.exitCode = 1;
    } else {
      console.log('Generated product spec files are current.');
    }
  } else {
    for (const [path, content] of Object.entries(outputs(readSources()))) {
      const absolute = resolve(defaultRoot, path);
      mkdirSync(dirname(absolute), { recursive: true });
      writeFileSync(absolute, content);
      console.log(`wrote ${path}`);
    }
  }
}
