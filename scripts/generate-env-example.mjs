#!/usr/bin/env node
// Regenerates the switch section of deploy/azure/api.env.example from the one switch table, packages/switches/src/table.ts
// (Syzygy ADR-0009 stage 1, D9). Only the switches in the table are written there; every other setting keeps its own section.
//
//   node scripts/generate-env-example.mjs           rewrite the section
//   node scripts/generate-env-example.mjs --check   exit 1 when the section is not what the table gives (verify.sh fast)

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const EXAMPLE = resolve(root, 'deploy/azure/api.env.example');
const BEGIN = '# --- Switches: generated by scripts/generate-env-example.mjs from packages/switches/src/table.ts; edit the table. ---';
const END = '# --- End of the generated switches. ---';

const READS = Object.freeze({
  default_on: 'on unless off/false/0/disabled/no/none',
  explicit_on: 'off unless on/true/1/yes',
  on_only: 'off unless on',
  true_only: 'off unless true',
});

/** The value written for a switch: its default, in the words its kind reads. */
export function exampleValue(entry) {
  if (entry.kind === 'true_only') return entry.default === 'on' ? 'true' : 'false';
  return entry.default;
}

/** The generated lines for one table entry: a comment and the assignment. */
export function entryLines(entry) {
  const needs = entry.requires.length ? ` Needs ${entry.requires.join(', ')}.` : '';
  return [`# ${entry.doc} [${entry.owner}; ${READS[entry.kind]}]${needs}`, `${entry.name}=${exampleValue(entry)}`];
}

/** The whole section, markers included. */
export function switchSection(switches) {
  return [BEGIN, ...switches.flatMap(entryLines), END].join('\n');
}

/** The example text with its section replaced (or appended when it has none). */
export function withSwitchSection(text, switches) {
  const section = switchSection(switches);
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start < 0 || end < start) return `${text.replace(/\n*$/u, '')}\n\n${section}\n`;
  return `${text.slice(0, start)}${section}${text.slice(end + END.length)}`;
}

async function main() {
  const { SWITCHES } = await import('../packages/switches/src/table.ts');
  const current = readFileSync(EXAMPLE, 'utf8');
  const next = withSwitchSection(current, SWITCHES);
  if (process.argv.includes('--check')) {
    if (next === current) {
      console.log(`Env example: the switch section matches the table (${SWITCHES.length} switches).`);
      return;
    }
    console.log('Env example: deploy/azure/api.env.example is out of date; run `node scripts/generate-env-example.mjs`.');
    process.exitCode = 1;
    return;
  }
  writeFileSync(EXAMPLE, next);
  console.log(`Env example: wrote ${SWITCHES.length} switches.`);
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  main().catch(error => {
    console.error(`generate-env-example: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 2;
  });
}
