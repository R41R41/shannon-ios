// Usage: node scripts/generate-minecraft-smelting.mjs <body smeltingRecipes.ts> [--check]
// The body's existing recipe definition is authoritative; no second hand-maintained table.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { stripTypeScriptTypes } from 'node:module';
const source = fs.readFileSync(process.argv[2], 'utf8').replace(/\r\n/g, '\n');
const { SMELTING_RECIPES } = await import(`data:text/javascript;base64,${Buffer.from(stripTypeScriptTypes(source)).toString('base64')}`);
const entries = Object.entries(SMELTING_RECIPES).sort(([a], [b]) => a.localeCompare(b));
if (entries.length < 20 || entries.some(([output, r]) => !/^[a-z_]+$/.test(output) || !/^[a-z_]+$/.test(r.input))) throw new Error('Invalid body recipe export');
const output = '// Generated by scripts/generate-minecraft-smelting.mjs; do not edit.\n'
  + `// Source: Shannon backend/src/services/minebot/knowledge/smeltingRecipes.ts sha256=${createHash('sha256').update(source).digest('hex')}\n`
  + `export const BODY_SMELTING_INPUT: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(entries.map(([name, recipe]) => [name, recipe.input])), null, 2)};\n`;
const destination = new URL('../services/api/src/surfaces/minecraft/minecraftSmelting.generated.ts', import.meta.url);
if (process.argv.includes('--check')) { if (fs.readFileSync(destination, 'utf8') !== output) throw new Error('Body recipe export drift'); }
else fs.writeFileSync(destination, output);
