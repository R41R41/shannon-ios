import { afterEach, expect, it } from 'vitest';
import { actionHarness } from './support/actionThreadHarness.js';
import { migrateAgentTasks } from '../src/mind/action/agentTasks/store/agentTaskPersistenceSupport.js';
import { SQLiteFcaTaskAuthority } from '../src/mind/action/agentTasks/store/fcaTaskAuthority.js';
import { SQLiteTaskRuntimeStore } from '../src/mind/action/taskRuntime/store/taskRuntimeStore.js';
import { actionResource, leaseOf } from '../src/contracts/actionThreadContract.js';
import { createFcaSourceGuard } from '../src/mind/action/fca/fcaConversationSources.js';
import { memoryWorld } from './support/memoryWorld.js';
import { ShannonMemoryService } from '../src/mind/memory/memoryService.js';
const close: Array<() => void> = [];
afterEach(() => close.splice(0).forEach(fn => fn()));
it('binds exact observed memory refs before history/child admission and persists them without a fake conversation', async () => {
  const at = '2026-10-09T00:00:00.000Z', h = actionHarness(() => at); close.push(h.close); migrateAgentTasks(h.db);
  let valid = true;
  const options = { authority: new SQLiteFcaTaskAuthority(h.db), now: () => at, leaseValid: () => valid };
  const runtime = new SQLiteTaskRuntimeStore(h.db, options), root = runtime.ensureRoot('owner');
  const task = runtime.createChild('owner', root.id, { title: 'parent', goal: 'research' }, 'parent');
  const action = await h.actions.claim((await h.actions.enqueue({ scopeKey: 'owner', sourceId: 'task-run', kind: 'agentTask', origin: 'owner_request', resources: [actionResource('owner', 'task')] })).id);
  const step = runtime.beginStep('owner', task.id, leaseOf(action!))!;
  const observation = { observationId: 'recall-one', recalledMemoryIds: ['memory-one'] };
  expect(runtime.observeSources(step, observation)).toBe(true); expect(runtime.observeSources(step, observation)).toBe(true);
  expect(runtime.observeSources(step, { ...observation, recalledMemoryIds: ['different'] })).toBe(false);
  expect(runtime.observeSources({ ...step, scopeKey: 'other' }, observation)).toBe(false);
  valid = false; expect(runtime.observeSources(step, { ...observation, observationId: 'stale' })).toBe(false); valid = true;
  const child = runtime.createChild('owner', task.id, { title: 'child', goal: 'follow up' }, 'child');
  const sources = runtime.taskSources('owner', child.id);
  expect(sources).toEqual([{ kind: 'memory', stepId: `memory:${step.id}:recall-one`, experienceId: null, threadId: null, observedAt: at, recalledMemoryIds: ['memory-one'] }]);
  step.snapshot.sources = runtime.taskSources('owner', task.id, step.messageIds);
  expect(runtime.commitStep(step, { disposition: 'wait', history: [{ role: 'user', content: 'derived text' }] })).not.toBeNull();
  const reopened = new SQLiteTaskRuntimeStore(h.db, options);
  expect(reopened.taskSources('owner', child.id)).toEqual(sources);
  expect(reopened.history('owner', task.id)?.rounds[0]?.sources).toEqual(sources);
});
it('withholds native task history derived from a now-forgotten memory, and denies missing canonical refs', async () => {
  const world = memoryWorld(); close.push(world.close);
  const h = actionHarness(world.now); close.push(h.close); migrateAgentTasks(h.db);
  const runtime = new SQLiteTaskRuntimeStore(h.db, { authority: new SQLiteFcaTaskAuthority(h.db), now: world.now, leaseValid: () => true });
  const root = runtime.ensureRoot('owner'), task = runtime.createChild('owner', root.id, { title: 'research', goal: 'research' }, 'child');
  const source = world.store.appendTurn('owner', 'thread', '望遠鏡の秘密', '観測した', world.now());
  const guard = createFcaSourceGuard({ runtime, state: world.store, conversations: world.store, ownerScope: 'owner', ownerAlone: () => true });
  const refs = [{ kind: 'memory' as const, stepId: 'memory:step:one', experienceId: null, threadId: null, observedAt: world.now(), recalledMemoryIds: [source.id] }];
  expect(guard.sources('owner', task, refs)).toBe(true);
  expect(guard.sources('owner', task, [{ ...refs[0]!, recalledMemoryIds: ['missing'] }])).toBe(false);
  world.advance(1000); new ShannonMemoryService(world.store, world.store, world.now).mutate('owner', { memoryId: source.id, action: 'forget' });
  expect(guard.sources('owner', task, refs)).toBe(false);
});
